    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        
        //Validasi
        if(txtJudul.getText().trim().isEmpty()
                || txtPenulis.getText().trim().isEmpty()
                || txtPenerbit.getText().trim().isEmpty()
                || txtTahun.getText().trim().isEmpty()
                || txtStok.getText().trim().isEmpty()){
           JOptionPane.showMessageDialog(this, "Semua data harus diisi!");
           return;
        }
        
        String judul = txtJudul.getText();
        String penulis = txtPenulis.getText();
        String penerbit = txtPenerbit.getText();
        
        try{
            int tahun = Integer.parseInt(txtTahun.getText());
            int stok = Integer.parseInt(txtStok.getText());
            
            int tahunSekarang = Year.now().getValue();
            
            if (tahun < 1000 || tahun > tahunSekarang){
                JOptionPane.showMessageDialog(this, "Tahun harus antara 1000 - " + tahunSekarang + "!");
                return;
            }
            
            if(stok <= 0 || stok > 1000){
                JOptionPane.showMessageDialog(this, "Stok harus lebih dari 0 dan kurang dari 1000!");
                return;
            }
            
            dao.insertBuku(judul, penulis, penerbit, tahun, stok);
        
            loadTable();
            resetForm();
            
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Tahun dan Stok harus berupa angka");
        }
        
    }//GEN-LAST:event_btnSimpanActionPerformed

