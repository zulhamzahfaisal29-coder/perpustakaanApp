    private void tblBukuMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblBukuMouseClicked
        int baris = tblBuku.getSelectedRow();
 
        idAnggota = Integer.parseInt(
                tblBuku.getValueAt(baris, 0).toString());
 
        txtNama.setText(
                tblBuku.getValueAt(baris, 1).toString());
 
        txtAlamat.setText(
                tblBuku.getValueAt(baris, 2).toString());
 
        txtTelepon.setText(
                tblBuku.getValueAt(baris, 3).toString());

        btnUpdate.setEnabled(true);
        btnHapus.setEnabled(true);
    }//GEN-LAST:event_tblBukuMouseClicked

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        
        if(idAnggota == 0){
            javax.swing.JOptionPane.showMessageDialog(this, "Pilih data dulu!");
            return;
        }
        
        int confirm = javax.swing.JOptionPane.showConfirmDialog(
                this,
                "Yakin mau hapus data ini",
                "Konfirmasi",
                javax.swing.JOptionPane.YES_NO_OPTION
        );
        
        if(confirm == javax.swing.JOptionPane.YES_OPTION){
            AnggotaDAO dao = new AnggotaDAO();
            dao.deleteAnggota(idAnggota);
            
            javax.swing.JOptionPane.showMessageDialog(this, "Berhasil dihapus");
            
            loadTable(); //refresh tabel
            resetForm();
        }
    }//GEN-LAST:event_btnHapusActionPerformed

