    private void loadTable(){
        DefaultTableModel model = new DefaultTableModel();
        
        model.addColumn("ID");
        model.addColumn("Nama");
        model.addColumn("Alamat");
        model.addColumn("Telepon");
        
        try{
            ResultSet rs;
            
            if(txtCari.getText().trim().isEmpty()){
                rs = dao.getAllAnggota();
            }else{
                rs = dao.cariAnggota(txtCari.getText());
            }
            
            while (rs.next()){
                
                model.addRow(new Object[]{
                    rs.getInt("id_anggota"),
                    rs.getString("nama"),
                    rs.getString("alamat"),
                    rs.getString("telepon"),
                });
            }
            
            tblBuku.setModel(model);
            
        }catch (Exception e){
            System.out.println("Error load table: " + e.getMessage());
        }
        
    }
    
    public void resetForm(){
        txtNama.setText("");
        txtAlamat.setText("");
        txtTelepon.setText("");
        txtCari.setText("");
        
        idAnggota = 0;
        
        tblBuku.clearSelection();
        
        
        btnUpdate.setEnabled(false);
        btnHapus.setEnabled(false);
        
        loadTable();
    }
    
